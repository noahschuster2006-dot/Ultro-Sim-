/** Icon for an action view: hand-picked, then keywords, then its category. */
export function actionIconFor(a: { id: string; label: string; cat?: string; group?: string }): LucideIcon {
  if (ACTION_ICON[a.id]) return ACTION_ICON[a.id];
  const text = `${a.label} ${a.id} ${a.group ?? ''}`;
  for (const [re, icon] of ACTION_KEYWORD_ICONS) if (re.test(text)) return icon;
  return (a.cat && ACTION_CAT_ICON[a.cat]) || Zap;
}
