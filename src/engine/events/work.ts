/** Modern dollars scaled to era money. */
const cash = (x: Ctx, n: number): number => Math.max(1, Math.round(n * eraCostFactor(x.year)));

/** Event condition: current career is in one of these categories. */
const inCat =
  (...cats: CareerCat[]) =>
  (x: Ctx): boolean => {
    const d = careerDef(x);
    return !!d && cats.includes(d.cat);
  };

const working = (x: Ctx): boolean => x.employed && !x.inPrison;
const jobless = (x: Ctx): boolean => !x.employed && !x.inPrison && x.age >= 18 && x.age < 66;
/** Ordinary (non-criminal, non-royal, non-occult) jobs. */
const ordinaryJob = (x: Ctx): boolean => {
  const d = careerDef(x);
  return working(x) && !!d && !['criminal', 'royalty', 'secret'].includes(d.cat);
};
const deskJob = (x: Ctx): boolean => working(x) && inCat('business', 'tech', 'legal', 'government', 'science', 'education')(x);
const jobName = (x: Ctx): string => (careerDef(x)?.name ?? 'job').toLowerCase();
const employer = (x: Ctx): string => x.c.career?.employer || 'the firm';
const title = (x: Ctx): string => (x.employed ? currentTitle(x) : 'nobody in particular');
const level = (x: Ctx): number => x.c.career?.level ?? 0;
const seniority = (x: Ctx): number => x.c.career?.yearsInCareer ?? 0;

function perf(x: Ctx, d: number): void {
  const c = x.c.career;
  if (c) c.performance = Math.max(0, Math.min(100, c.performance + d));
}

/** Give a raise of pct; returns the yearly amount added. */
function raise(x: Ctx, pct: number): number {
  const c = x.c.career;
  if (!c) return 0;
  const add = Math.max(1, Math.round(c.salary * pct));
  c.salary += add;
  return add;
}

/** Try to promote; describe the result. */
function rise(x: Ctx, yes: (t: string) => string, no: string): string {
  const t = promote(x);
  return t ? yes(t) : no;
}

function sack(x: Ctx, reason: string, text: string): string {
  endCareer(x, reason);
  x.mods({ happiness: -8, stress: 8, confidence: -4 });
  return text;
}

/** Take a random ordinary job the character qualifies for. */
function takeAnyJob(x: Ctx): string | null {
  const opts = visibleCareers(x).filter((d) => !['criminal', 'royalty', 'secret', 'politics'].includes(d.cat) && careerEligibility(x, d) === true);
  if (!opts.length) return null;
  const def = x.pick(opts);
  startCareer(x, def);
  return def.name.toLowerCase();
}

const message = (x: Ctx): string => (x.year < 1880 ? 'letter' : x.year < 1990 ? 'memo' : x.year < 2010 ? 'email' : 'message');

