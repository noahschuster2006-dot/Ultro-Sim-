export type SkillCategory = (typeof SKILL_CATEGORIES)[number]['id'];

export interface SkillDef {
  id: string;
  name: string;
  cat: SkillCategory;
  prereq?: string;
  fromYear?: number;
  /** Hidden until a supernatural or criminal precondition is met. */
  hidden?: boolean;
}

export const UNLOCK_LEVEL = 25;

type Row = [id: string, name: string, prereq?: string, fromYear?: number, hidden?: boolean];

function tree(cat: SkillCategory, rows: Row[]): SkillDef[] {
  return rows.map(([id, name, prereq, fromYear, hidden]) => ({ id, name, cat, prereq, fromYear, hidden }));
}

